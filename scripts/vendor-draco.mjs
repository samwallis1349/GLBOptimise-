/**
 * Copies the Draco glTF decoder glue from Three.js into
 * worker/api/vendor/draco_decoder.js with the Node fs/require check disabled
 * and an ES module default export. This allows Cloudflare Workers (workerd)
 * and Node tests to instantiate the Draco decoder via instantiateWasm without
 * dynamic code evaluation (`new Function` / `eval`) or `fs`.
 *
 * Re-run after upgrading three: node scripts/vendor-draco.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const src = new URL('../node_modules/three/examples/jsm/libs/draco/gltf/draco_wasm_wrapper.js', import.meta.url);
const out = new URL('../worker/api/vendor/draco_decoder.js', import.meta.url);
let code = readFileSync(src, 'utf8');

const nodeCheck = 'Ua="object"==typeof process&&"object"==typeof process.versions&&"string"==typeof process.versions.node';
if (!code.includes(nodeCheck)) {
  throw new Error('Node environment check (Ua=...) not found in draco_wasm_wrapper.js; update scripts/vendor-draco.mjs.');
}
code = code.replace(nodeCheck, 'Ua=false');

const cjsFooter = '"object"===typeof exports&&"object"===typeof module?module.exports=DracoDecoderModule:"function"===typeof define&&define.amd?define([],function(){return DracoDecoderModule}):"object"===typeof exports&&(exports.DracoDecoderModule=DracoDecoderModule);';
if (!code.includes(cjsFooter)) {
  throw new Error('CJS footer not found in draco_wasm_wrapper.js; update scripts/vendor-draco.mjs.');
}
code = code.replace(cjsFooter, 'export default DracoDecoderModule;');

if (/new Function\(|\beval\(/.test(code)) {
  throw new Error('Dynamic code evaluation (new Function / eval) is still present in draco_decoder.js.');
}

writeFileSync(out, `// GENERATED by scripts/vendor-draco.mjs from three's draco_wasm_wrapper.js. Do not edit.\n${code}`);
console.log('wrote', out.pathname);
